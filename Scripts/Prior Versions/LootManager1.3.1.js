    async function handleUnlockCheck(msg, looterTokenId, containerTokenId) {
        const looterToken = resolveToken(msg, looterTokenId);
        const containerToken = resolveToken(msg, containerTokenId);
        let loot;
        let characterId;
        let lockDc;
        let bonus;
        let naturalRoll;
        let total;
        let success;
        let persisted;

        if (!looterToken || !containerToken) {
            sendError(msg, 'The looter token or container token no longer exists.');
            return;
        }

        loot = getLoot(containerToken);

        if (!loot.block) {
            sendError(msg, 'The target no longer has a valid LOOT block.');
            return;
        }

        if (!isContainer(loot)) {
            sendError(msg, 'The target is no longer marked as a container.');
            return;
        }

        if (!loot.container.locked) {
            await inspectLoot(msg, looterToken, containerToken);
            return;
        }

        characterId = String(looterToken.get('represents') || '');

        if (!characterId) {
            sendError(msg, 'The looter token must represent a Beacon character.');
            return;
        }

        lockDc = parseFiniteNumber(loot.container.lockDc);

        if (lockDc === null) {
            sendGmWarning(
                String(containerToken.get('name') || 'Container') +
                ' has a missing or invalid lock-dc value.'
            );
            sendError(msg, 'This container does not have a valid lock DC.');
            return;
        }

        if (typeof getSheetItem !== 'function') {
            sendError(msg, 'Beacon getSheetItem is unavailable, so the lock check cannot be made.');
            return;
        }

        if (activeUnlocks[containerToken.id]) {
            sendError(msg, 'A lock check for this container is already processing.');
            return;
        }

        activeUnlocks[containerToken.id] = true;

        try {
            loot = getLoot(containerToken);

            if (!loot.block || !isContainer(loot)) {
                sendError(msg, 'The container configuration changed before the check could begin.');
                return;
            }

            if (!loot.container.locked) {
                await inspectLoot(msg, looterToken, containerToken);
                return;
            }

            lockDc = parseFiniteNumber(loot.container.lockDc);

            if (lockDc === null) {
                sendGmWarning(
                    String(containerToken.get('name') || 'Container') +
                    ' has a missing or invalid current lock-dc value.'
                );
                sendError(msg, 'This container no longer has a valid lock DC.');
                return;
            }

            setContainerSide(containerToken, loot.container.closedSide, 'closed');

            try {
                bonus = parseFiniteNumber(
                    await getSheetItem(characterId, 'sleight_of_hand_bonus')
                );
            } catch (error) {
                log(SCRIPT + ': Sleight of Hand bonus read failed: ' + error);
                sendError(msg, 'The character\'s Sleight of Hand bonus could not be read.');
                return;
            }

            if (bonus === null) {
                sendError(msg, 'The character has an invalid Sleight of Hand bonus.');
                return;
            }

            try {
                naturalRoll = await evaluateRollExpression('1d20');
            } catch (error) {
                log(SCRIPT + ': Sleight of Hand d20 roll failed: ' + error);
                sendError(msg, 'Roll20 could not complete the Sleight of Hand check.');
                return;
            }

            total = naturalRoll + bonus;

            if (!isFinite(naturalRoll) || !isFinite(total)) {
                sendError(msg, 'The Sleight of Hand check returned an invalid result.');
                return;
            }

            success = total >= lockDc;

            if (!success) {
                showUnlockResultCard(
                    msg,
                    looterToken,
                    containerToken,
                    naturalRoll,
                    bonus,
                    total,
                    lockDc,
                    false
                );
                return;
            }

            if (!setContainerLocked(loot, false)) {
                sendError(msg, 'The container lock setting could not be updated.');
                return;
            }

            try {
                if (!writeLoot(containerToken, loot)) {
                    throw new Error('The LOOT block could not be written.');
                }
            } catch (error) {
                log(SCRIPT + ': Container unlock GM Notes write failed: ' + error);
                sendGmWarning(
                    'The lock check succeeded for ' +
                    String(containerToken.get('name') || 'container') +
                    ', but locked: no could not be written: ' + error
                );
                sendError(msg, 'The check succeeded, but the unlocked state could not be saved.');
                return;
            }

            persisted = getLoot(containerToken);

            if (!isContainer(persisted) || persisted.container.locked) {
                sendGmWarning(
                    'The unlocked state for ' +
                    String(containerToken.get('name') || 'container') +
                    ' could not be verified in GM Notes.'
                );
                sendError(msg, 'The check succeeded, but the unlocked state could not be verified.');
                return;
            }

            showUnlockResultCard(
                msg,
                looterToken,
                containerToken,
                naturalRoll,
                bonus,
                total,
                lockDc,
                true
            );
            if (!setContainerSide(containerToken, persisted.container.openSide, 'open')) {
                sendError(msg, 'The lock was opened, but the container image could not be changed.');
            }
            playSound(getConfig().itemSound);
            await inspectLoot(
                msg,
                looterToken,
                containerToken,
                {
                    skipContainerSide: true
                }
            );
        } finally {
            delete activeUnlocks[containerToken.id];
        }
    }

    async function handleUseKey(msg, looterTokenId, containerTokenId, options) {
        const looterToken = resolveToken(msg, looterTokenId);
        const containerToken = resolveToken(msg, containerTokenId);
        const expectedKey = normalizeKeyName(decodeOption(options.key));
        let loot;
        let characterId;
        let character;
        let persisted;

        if (!looterToken || !containerToken) {
            sendError(msg, 'The looter token or container token no longer exists.');
            return;
        }

        loot = getLoot(containerToken);

        if (!loot.block) {
            sendError(msg, 'The target no longer has a valid LOOT block.');
            return;
        }

        if (!isContainer(loot)) {
            sendError(msg, 'The target is no longer marked as a container.');
            return;
        }

        if (!loot.container.locked) {
            await inspectLoot(msg, looterToken, containerToken);
            return;
        }

        characterId = String(looterToken.get('represents') || '');
        character = characterId ? getObj('character', characterId) : null;

        if (!characterId || !character) {
            sendError(msg, 'The looter token must represent a current character to use a key.');
            return;
        }

        if (
            !expectedKey ||
            !loot.container.keyNormalized ||
            loot.container.keyNormalized !== expectedKey ||
            !characterHasKey(characterId, expectedKey)
        ) {
            await staleCard(msg, containerToken, looterToken);
            return;
        }

        if (activeUnlocks[containerToken.id]) {
            sendError(msg, 'A container unlock is already processing.');
            return;
        }

        activeUnlocks[containerToken.id] = true;

        try {
            loot = getLoot(containerToken);

            if (!loot.block || !isContainer(loot)) {
                sendError(msg, 'The container configuration changed before the key could be used.');
                return;
            }

            if (!loot.container.locked) {
                await inspectLoot(msg, looterToken, containerToken);
                return;
            }

            if (
                !loot.container.keyNormalized ||
                loot.container.keyNormalized !== expectedKey ||
                !characterHasKey(characterId, expectedKey)
            ) {
                await staleCard(msg, containerToken, looterToken);
                return;
            }

            if (!setContainerLocked(loot, false)) {
                sendError(msg, 'The container lock setting could not be updated.');
                return;
            }

            try {
                if (!writeLoot(containerToken, loot)) {
                    throw new Error('The LOOT block could not be written.');
                }
            } catch (error) {
                log(SCRIPT + ': Key unlock GM Notes write failed: ' + error);
                sendGmWarning(
                    'Key unlock for ' +
                    String(containerToken.get('name') || 'container') +
                    ' could not write locked: no: ' + error
                );
                sendError(msg, 'The key fits, but the unlocked state could not be saved.');
                return;
            }

            persisted = getLoot(containerToken);

            if (
                !isContainer(persisted) ||
                persisted.container.locked ||
                persisted.container.keyNormalized !== expectedKey
            ) {
                sendGmWarning(
                    'The key unlock state for ' +
                    String(containerToken.get('name') || 'container') +
                    ' could not be verified in GM Notes.'
                );
                sendError(msg, 'The key fit, but the unlocked state could not be verified.');
                return;
            }

            setContainerSide(containerToken, persisted.container.openSide, 'open');
            playSound(getConfig().itemSound);
            await inspectLoot(
                msg,
                looterToken,
                containerToken,
                {
                    skipContainerSide: true
                }
            );
        } finally {
            delete activeUnlocks[containerToken.id];
        }
    }

    function parseToggle(value) {
        const normalized = String(value || '').trim().toLowerCase();

        if (/^(?:on|yes|true|1)$/.test(normalized)) return true;
        if (/^(?:off|no|false|0)$/.test(normalized)) return false;
        return null;
    }

