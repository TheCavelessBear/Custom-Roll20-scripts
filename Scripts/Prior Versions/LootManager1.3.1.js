    function getKeyringSummaries() {
        const keys = getKeyState();

        return Object.keys(keys).map(function(characterId) {
            const character = getObj('character', characterId);

            return {
                characterId: characterId,
                character: character,
                name: character
                    ? String(character.get('name') || 'Unnamed Character')
                    : 'Missing Character',
                keyCount: countKeyRecords(keys[characterId])
            };
        }).sort(function(left, right) {
            if (!!left.character !== !!right.character) {
                return left.character ? -1 : 1;
            }

            const nameComparison = left.name.toLowerCase().localeCompare(right.name.toLowerCase());

            return nameComparison || left.characterId.localeCompare(right.characterId);
        });
    }

