    async function takeHandout(msg, token, options) {
        const loot = getLoot(token);
        const index = parseNonNegativeInteger(options.index);
        const sourceIndex = parseNonNegativeInteger(options['source-index']);
        const expectedName = decodeOption(options.name);
        const expectedBefore = decodeOption(options.before);
        const expectedAfter = decodeOption(options.after);
        const handout = index === null ? null : loot.handouts.find(function(entry) {
            return entry.index === index;
        });
        const recordIndex = handout ? loot.records.indexOf(handout) : -1;
        const currentBefore = recordIndex > 0
            ? loot.records[recordIndex - 1].raw
            : 'LOOT';
        const currentAfter = recordIndex >= 0 && recordIndex < loot.records.length - 1
            ? loot.records[recordIndex + 1].raw
            : 'END LOOT';
        let result;
        let matchingEntries;

        if (
            !loot.block ||
            (isContainer(loot) && loot.container.locked) ||
            loot.unresolvedGp.length > 0 ||
            !handout ||
            sourceIndex === null ||
            handout.sourceIndex !== sourceIndex ||
            handout.name !== expectedName ||
            currentBefore !== expectedBefore ||
            currentAfter !== expectedAfter
        ) {
            await staleCard(msg, token);
            return;
        }

        if (
            typeof HandoutAccess === 'undefined' ||
            !HandoutAccess ||
            typeof HandoutAccess.revealByReference !== 'function'
        ) {
            sendGmWarning(
                'HandoutAccess.revealByReference is unavailable. Handout "' +
                handout.name + '" remains in ' +
                String(token.get('name') || 'the loot source') + '.'
            );
            sendError(msg, 'Handout access is unavailable. The handout remains in the loot.');
            return;
        }

        try {
            result = HandoutAccess.revealByReference(
                handout.name,
                msg.playerid,
                {
                    announce: true
                }
            );
        } catch (error) {
            log(SCRIPT + ': HandoutAccess reveal failed: ' + error);
            sendGmWarning(
                'Handout "' + handout.name + '" could not be granted: ' + error
            );
            sendError(msg, 'The handout could not be granted. The handout remains in the loot.');
            return;
        }

        if (!result || result.ok !== true) {
            sendGmWarning(
                'Handout "' + handout.name + '" could not be granted: ' +
                String(result && result.error || 'HandoutAccess did not return success.')
            );
            sendError(msg, 'The handout could not be granted. The handout remains in the loot.');
            return;
        }

        matchingEntries = loot.handouts.filter(function(entry) {
            return entry.name === handout.name;
        }).length;
        handout.removed = true;

        await finalizeStructuredTake(
            msg,
            token,
            loot,
            getConfig().itemSound,
            handout.name + ' handout',
            {
                writeBeforeDelete: true,
                verifyWrite: function(persisted) {
                    return persisted.handouts.filter(function(entry) {
                        return entry.name === handout.name;
                    }).length === matchingEntries - 1;
                },
                playerWriteError: 'Handout access was granted, but the loot entry could not be removed.',
                gmWriteError: 'Handout "' + handout.name + '" was granted to ' +
                    getPlayerName(msg) + ', but the loot entry could not be removed. ' +
                    'The player still has access to the handout.'
            }
        );
    }

    async function takeKey(msg, token, options) {
        const loot = getLoot(token);
        const index = parseNonNegativeInteger(options.index);
        const sourceIndex = parseNonNegativeInteger(options['source-index']);
        const expectedName = decodeOption(options.name);
        const expectedBefore = decodeOption(options.before);
        const expectedAfter = decodeOption(options.after);
        const keyItem = index === null ? null : loot.keyItems.find(function(entry) {
            return entry.index === index;
        });
        const recordIndex = keyItem ? loot.records.indexOf(keyItem) : -1;
        const currentBefore = recordIndex > 0
            ? loot.records[recordIndex - 1].raw
            : 'LOOT';
        const currentAfter = recordIndex >= 0 && recordIndex < loot.records.length - 1
            ? loot.records[recordIndex + 1].raw
            : 'END LOOT';
        const looterToken = resolveToken(msg, options.looter);
        const characterId = String(looterToken && looterToken.get('represents') || '');
        const character = characterId ? getObj('character', characterId) : null;
        let matchingEntries;
        let keyResult;

        if (
            !loot.block ||
            (isContainer(loot) && loot.container.locked) ||
            loot.unresolvedGp.length > 0 ||
            !keyItem ||
            sourceIndex === null ||
            keyItem.sourceIndex !== sourceIndex ||
            keyItem.name !== expectedName ||
            currentBefore !== expectedBefore ||
            currentAfter !== expectedAfter
        ) {
            await staleCard(msg, token);
            return;
        }

        if (!looterToken) {
            sendError(msg, 'Select a valid linked looter token, then use the key button again.');
            return;
        }

        if (!characterId) {
            sendError(msg, 'The looter token must represent a character to take a key.');
            return;
        }

        if (!character) {
            sendError(msg, 'The looter token represents a character that no longer exists.');
            return;
        }

        keyResult = grantCharacterKey(characterId, keyItem.name);

        if (!keyResult.ok) {
            sendError(msg, 'The key name is invalid. The loot was not changed.');
            return;
        }

        matchingEntries = loot.keyItems.filter(function(entry) {
            return entry.name === keyItem.name;
        }).length;
        keyItem.removed = true;

        await finalizeStructuredTake(
            msg,
            token,
            loot,
            getConfig().itemSound,
            keyResult.name,
            {
                writeBeforeDelete: true,
                verifyWrite: function(persisted) {
                    return persisted.keyItems.filter(function(entry) {
                        return entry.name === keyItem.name;
                    }).length === matchingEntries - 1;
                },
                playerWriteError: 'The key was added, but the loot entry could not be removed.',
                gmWriteError: 'Key "' + keyResult.name + '" was added to ' +
                    String(character.get('name') || characterId) +
                    ', but the loot entry could not be removed.'
            }
        );
    }

    async function takeLooseItem(msg, token, options) {
        const loot = getLoot(token);
        const expectedName = decodeOption(options.name);
        const currentName = String(token.get('name') || 'Loose Item');

        if (token.get('represents') || loot.block || currentName !== expectedName) {
            await staleCard(msg, token);
            return;
        }

        token.remove();
        playSound(getConfig().itemSound);
        announceTake(msg, currentName, currentName);
    }

    async function handleTake(msg, options) {
        const token = resolveToken(msg, options.token);
        const type = String(options.type || '').toLowerCase();

        if (!token) {
            sendError(msg, 'The loot source no longer exists.');
            return;
        }

        if (activeTakes[token.id]) {
            sendError(msg, 'Another take from this source is still processing. Inspect it again before retrying.');
            return;
        }

        activeTakes[token.id] = true;

        try {
            switch (type) {
                case 'gp':
                    await takeGp(msg, token, options);
                    break;

                case 'item':
                    await takeItem(msg, token, options);
                    break;

                case 'handout':
                    await takeHandout(msg, token, options);
                    break;

                case 'key':
                    await takeKey(msg, token, options);
                    break;

                case 'loose':
                    await takeLooseItem(msg, token, options);
                    break;

                default:
                    sendError(msg, 'Unknown loot type. Inspect the source to create a fresh button.');
                    break;
            }
        } finally {
            delete activeTakes[token.id];
        }
    }

