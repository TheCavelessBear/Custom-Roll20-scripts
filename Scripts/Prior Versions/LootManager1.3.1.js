    async function handleInput(msg) {
        const command = parseCommand(msg.content);
        const knownActions = {
            inspect: true,
            show: true,
            take: true,
            'unlock-check': true,
            'use-key': true,
            config: true,
            keys: true,
            help: true
        };
        let looterToken;
        let token;

        if (msg.type !== 'api' || !/^!loot(?:\s|$)/i.test(msg.content)) return;

        if (
            !knownActions[command.action] &&
            command.actionRaw &&
            command.positionals.length === 1
        ) {
            looterToken = resolveToken(msg, command.actionRaw);
            token = resolveToken(msg, command.positionals[0]);

            if (!looterToken || !token) {
                sendError(msg, 'The selected looter token or targeted loot token is invalid.');
                return;
            }

            await inspectLoot(msg, looterToken, token);
            return;
        }

        switch (command.action) {
            case 'inspect':
            case 'show':
                token = resolveToken(msg, command.options.token);

                if (!token) {
                    sendError(msg, 'Select a token or specify one with --token|TOKEN_ID.');
                    return;
                }

                await inspectLoot(msg, null, token);
                break;

            case 'take':
                await handleTake(msg, command.options);
                break;

            case 'unlock-check':
                if (command.positionals.length !== 2) {
                    sendError(
                        msg,
                        'Use !loot unlock-check LOOTER_TOKEN_ID CONTAINER_TOKEN_ID.'
                    );
                    return;
                }

                await handleUnlockCheck(
                    msg,
                    command.positionals[0],
                    command.positionals[1]
                );
                break;

            case 'use-key':
                if (command.positionals.length !== 2) {
                    sendError(
                        msg,
                        'Use !loot use-key LOOTER_TOKEN_ID CONTAINER_TOKEN_ID.'
                    );
                    return;
                }

                await handleUseKey(
                    msg,
                    command.positionals[0],
                    command.positionals[1],
                    command.options
                );
                break;

            case 'config':
                handleConfig(msg, command.options);
                break;

            case 'keys':
                handleKeys(msg, command);
                break;

            case 'help':
                showHelp(msg);
                break;

            default:
                sendError(msg, 'Unknown command. Use !loot help for the command list.');
                break;
        }
    }

    function registerEventHandlers() {
        on('chat:message', function(msg) {
            handleInput(msg).catch(function(error) {
                log(SCRIPT + ': Unexpected error: ' + error);
                sendError(msg, 'An unexpected error occurred. No further loot changes were attempted.');
            });
        });
    }

