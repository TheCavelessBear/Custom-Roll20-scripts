    function pruneKeyrings() {
        const keys = getKeyState();
        let missingCharacterRecords = 0;
        let emptyOrMalformedRecords = 0;
        let normalizedKeyRecords = 0;
        let retainedKeyrings = 0;
        let retainedKeyRecords = 0;

        Object.keys(keys).forEach(function(characterId) {
            const keyring = keys[characterId];

            if (!getObj('character', characterId)) {
                delete keys[characterId];
                missingCharacterRecords += 1;
                return;
            }

            if (!isKeyring(keyring)) {
                delete keys[characterId];
                emptyOrMalformedRecords += 1;
                return;
            }

            Object.keys(keyring).forEach(function(normalizedName) {
                const record = keyring[normalizedName];
                const name = record && typeof record.name === 'string'
                    ? cleanKeyName(record.name)
                    : '';
                const canonicalName = normalizeKeyName(name);
                const existingRecord = keyring[canonicalName];
                const existingName = existingRecord && typeof existingRecord.name === 'string'
                    ? cleanKeyName(existingRecord.name)
                    : '';

                if (
                    !name ||
                    !canonicalName
                ) {
                    delete keyring[normalizedName];
                    emptyOrMalformedRecords += 1;
                    return;
                }

                if (normalizedName !== canonicalName) {
                    if (
                        !existingName ||
                        normalizeKeyName(existingName) !== canonicalName
                    ) {
                        keyring[canonicalName] = {
                            name: name
                        };
                    }

                    delete keyring[normalizedName];
                    normalizedKeyRecords += 1;
                    return;
                }

                record.name = name;
            });

            if (!Object.keys(keyring).length) {
                delete keys[characterId];
                emptyOrMalformedRecords += 1;
                return;
            }

            retainedKeyrings += 1;
            retainedKeyRecords += Object.keys(keyring).length;
        });

        return {
            missingCharacterRecords: missingCharacterRecords,
            emptyOrMalformedRecords: emptyOrMalformedRecords,
            normalizedKeyRecords: normalizedKeyRecords,
            retainedKeyrings: retainedKeyrings,
            retainedKeyRecords: retainedKeyRecords
        };
    }

    function handleKeys(msg, command) {
        const action = String(command.positionals[0] || '').toLowerCase();
        const options = command.options || {};
        const characterId = decodeOption(options.character);
        const keyName = decodeOption(options.key);
        const confirmation = String(options.confirm || '').trim().toLowerCase();
        const character = characterId ? getObj('character', characterId) : null;
        let result;
        let removedCount;
        let summary;
        let keyringCount;
        let keyRecordCount;

        if (!playerIsGM(msg.playerid)) {
            sendError(msg, 'Only the GM can manage LootManager keyrings.');
            return;
        }

        switch (action) {
            case '':
                if (characterId) {
                    showCharacterKeyring(msg, characterId);
                } else {
                    showKeysMenu(msg, options.page);
                }
                break;

            case 'grant':
                if (!characterId || !character) {
                    sendError(msg, 'Specify an existing character before granting a key.');
                    return;
                }

                if (!cleanKeyName(keyName)) {
                    sendError(msg, 'Specify a nonblank key name.');
                    return;
                }

                result = grantCharacterKey(characterId, keyName);

                if (!result.ok) {
                    sendError(msg, 'The key name is invalid.');
                    return;
                }

                showCharacterKeyring(
                    msg,
                    characterId,
                    result.added
                        ? 'Granted ' + result.name + '.'
                        : result.name + ' was already present.'
                );
                break;

            case 'remove':
                if (!characterId || !cleanKeyName(keyName)) {
                    sendError(msg, 'Specify a character and key to remove.');
                    return;
                }

                if (!removeCharacterKey(characterId, keyName)) {
                    sendError(msg, 'That key is no longer in the character keyring.');
                    return;
                }

                if (getKeyring(characterId, false)) {
                    showCharacterKeyring(msg, characterId, 'Removed the selected key.');
                } else {
                    showKeysMenu(msg, options.page, 'Removed the selected keyring entry.');
                }
                break;

            case 'clear-character':
                if (!characterId) {
                    sendError(msg, 'Specify a character keyring to clear.');
                    return;
                }

                if (confirmation !== 'yes') {
                    sendError(msg, 'Clear Character Keyring requires --confirm|yes.');
                    return;
                }

                removedCount = countKeyRecords(getKeyring(characterId, false));
                delete getKeyState()[characterId];
                showKeysMenu(
                    msg,
                    options.page,
                    'Removed ' + removedCount + ' key record' +
                    (removedCount === 1 ? '' : 's') + '.'
                );
                break;

            case 'prune':
                summary = pruneKeyrings();
                showKeysMenu(
                    msg,
                    options.page,
                    'Pruned ' + summary.missingCharacterRecords +
                    ' missing-character record' +
                    (summary.missingCharacterRecords === 1 ? '' : 's') +
                    ' and ' + summary.emptyOrMalformedRecords +
                    ' empty or malformed record' +
                    (summary.emptyOrMalformedRecords === 1 ? '' : 's') +
                    ', normalized or coalesced ' + summary.normalizedKeyRecords +
                    ' key record' + (summary.normalizedKeyRecords === 1 ? '' : 's') +
                    '. Retained ' + summary.retainedKeyrings +
                    ' valid keyring' + (summary.retainedKeyrings === 1 ? '' : 's') +
                    ' with ' + summary.retainedKeyRecords + ' valid key record' +
                    (summary.retainedKeyRecords === 1 ? '' : 's') + '.'
                );
                break;

            case 'clear-all':
                if (confirmation !== 'yes') {
                    sendError(msg, 'Clear All Keyrings requires --confirm|yes.');
                    return;
                }

                keyringCount = Object.keys(getKeyState()).length;
                keyRecordCount = Object.keys(getKeyState()).reduce(function(total, currentCharacterId) {
                    return total + countKeyRecords(getKeyState()[currentCharacterId]);
                }, 0);
                state.LootManager.keys = {};
                showKeysMenu(
                    msg,
                    options.page,
                    'Removed ' + keyringCount + ' character keyring' +
                    (keyringCount === 1 ? '' : 's') + ' and ' + keyRecordCount +
                    ' key record' + (keyRecordCount === 1 ? '' : 's') + '.'
                );
                break;

            default:
                sendError(msg, 'Unknown keyring command. Use !loot keys to open the keyring menu.');
                break;
        }
    }

