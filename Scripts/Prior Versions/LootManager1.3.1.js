    function getCleanTokenImgsrc(imgsrc) {
        const rawSource = String(imgsrc || '');
        let cleanSource = rawSource;
        let match;

        try {
            cleanSource = decodeURIComponent(rawSource);
        } catch (error) {
            cleanSource = rawSource;
        }

        match = cleanSource.match(/(.*\/images\/.*)(thumb|med|original|max)([^?]*)(\?[^?]+)?$/);
        if (!match) return null;

        return match[1] + 'thumb' + match[3] + (match[4] || '');
    }

    function setContainerSide(token, sideValue, label) {
        const configuredSide = parseNonNegativeInteger(sideValue);
        const rawSides = String(token && token.get('sides') || '');
        const sides = rawSides ? rawSides.split('|').filter(function(side) {
            return side !== '';
        }) : [];
        let imgsrc;

        if (!token) return false;

        if (sides.length < 2) {
            sendGmWarning(
                String(token.get('name') || 'Container') +
                ' is not a multi-sided token; its ' + label + ' side could not be set.'
            );
            return false;
        }

        if (configuredSide === null || configuredSide < 1) {
            sendGmWarning(
                String(token.get('name') || 'Container') +
                ' has no valid positive-integer ' + label + '-side setting.'
            );
            return false;
        }

        if (configuredSide > sides.length) {
            sendGmWarning(
                String(token.get('name') || 'Container') + ' has ' + sides.length +
                ' sides, so configured ' + label + '-side ' + configuredSide + ' is out of range.'
            );
            return false;
        }

        imgsrc = getCleanTokenImgsrc(sides[configuredSide - 1]);

        if (!imgsrc) {
            sendGmWarning(
                String(token.get('name') || 'Container') +
                ' has an unusable image URL for configured ' + label + '-side ' + configuredSide + '.'
            );
            return false;
        }

        try {
            token.set({
                currentSide: configuredSide - 1,
                imgsrc: imgsrc
            });
        } catch (error) {
            log(SCRIPT + ': Container side update failed: ' + error);
            sendGmWarning(
                String(token.get('name') || 'Container') +
                ' could not change to configured ' + label + '-side ' + configuredSide + '.'
            );
            return false;
        }

        return true;
    }

